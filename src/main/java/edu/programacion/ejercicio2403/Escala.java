package edu.programacion.ejercicio2403;

    /**
     * Representa las diferentes escalas de temperatura
     * utilizadas por la clase {@link Temperatura}.
     *
     * @author Gisela Acosta
     * @version 1.0
     */
    public enum Escala {

        /**
         * Escala Celsius.
         */
        CELSIUS,

        /**
         * Escala Fahrenheit.
         */
        FAHRENHEIT,

        /**
         * Escala Kelvin.
         */
        KELVIN,

        /**
         * Escala Rankine.
         */
        RANKINE,

        /**
         * Escala Réaumur.
         */
        REAUMUR
    }